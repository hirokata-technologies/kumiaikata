-- The next key for (workspace, prefix). The upsert takes the counter row's lock, so two
-- concurrent allocations serialize; a rolled-back allocation gives its number back.
CREATE OR REPLACE FUNCTION kumiai_allocate_key(p_workspace_id text, p_prefix text) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE n integer;
BEGIN
  INSERT INTO kumiai_key_counters (workspace_id, prefix, next) VALUES (p_workspace_id, p_prefix, 2)
  ON CONFLICT (workspace_id, prefix) DO UPDATE SET next = kumiai_key_counters.next + 1
  RETURNING next - 1 INTO n;
  RETURN kumiai_format_key(p_prefix, n);
END $$;--> statement-breakpoint
