-- =====================================================================================
-- SCOPE: every guild row lives in exactly one workspace, and so does everything it points
-- at. BEFORE INSERT/UPDATE, with (parent_table, fk_column) pairs as arguments:
--   * workspace_id and team_id are filled from the first non-NULL parent when NULL,
--   * every non-NULL parent must exist and sit in the SAME workspace,
--   * team_id must be the workspace's team,
--   * inside withGuildTx (`kumiai.workspace_id` set), the row must be in that workspace.
-- An unaffiliated requirement with no workspace gets its team's default workspace.
-- =====================================================================================
CREATE OR REPLACE FUNCTION kumiai_guild_scope() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  rec jsonb := to_jsonb(NEW);
  old_rec jsonb := CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(OLD) ELSE NULL END;
  ws text := rec->>'workspace_id';
  team text := rec->>'team_id';
  ctx_ws text := NULLIF(current_setting('kumiai.workspace_id', true), '');
  i integer := 0;
  changed boolean := TG_OP = 'INSERT';
  parent_table text;
  fk_col text;
  fk_val text;
  p_ws text;
  p_team text;
BEGIN
  IF NOT changed THEN
    changed := (rec->'workspace_id') IS DISTINCT FROM (old_rec->'workspace_id')
            OR (rec->'team_id') IS DISTINCT FROM (old_rec->'team_id');
    WHILE NOT changed AND i < TG_NARGS LOOP
      changed := (rec->TG_ARGV[i + 1]) IS DISTINCT FROM (old_rec->TG_ARGV[i + 1]);
      i := i + 2;
    END LOOP;
    IF NOT changed THEN RETURN NEW; END IF;
    i := 0;
  END IF;

  WHILE i < TG_NARGS LOOP
    parent_table := TG_ARGV[i];
    fk_col := TG_ARGV[i + 1];
    i := i + 2;
    fk_val := rec->>fk_col;
    CONTINUE WHEN fk_val IS NULL;
    EXECUTE format('SELECT workspace_id FROM %I WHERE id = $1', parent_table) INTO p_ws USING fk_val;
    IF p_ws IS NULL THEN
      RAISE EXCEPTION 'kumiai: %.% = % does not exist', TG_TABLE_NAME, fk_col, fk_val
        USING ERRCODE = 'foreign_key_violation';
    END IF;
    IF ws IS NULL THEN
      ws := p_ws;
    ELSIF ws <> p_ws THEN
      RAISE EXCEPTION 'kumiai: % row is in workspace % but its % is in workspace %', TG_TABLE_NAME, ws, fk_col, p_ws
        USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;

  IF ws IS NULL AND TG_TABLE_NAME = 'kumiai_requirements' AND team IS NOT NULL THEN
    SELECT w.id INTO ws FROM kumiai_workspaces w WHERE w.team_id = team AND w.is_default;
  END IF;

  IF ws IS NOT NULL THEN
    SELECT w.team_id INTO p_team FROM kumiai_workspaces w WHERE w.id = ws;
    IF team IS NULL THEN
      team := p_team;
    ELSIF p_team IS NOT NULL AND team <> p_team THEN
      RAISE EXCEPTION 'kumiai: % row has team % but workspace % belongs to team %', TG_TABLE_NAME, team, ws, p_team
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  IF ctx_ws IS NOT NULL AND ws IS DISTINCT FROM ctx_ws THEN
    RAISE EXCEPTION 'kumiai: % row is in workspace %, outside this transaction''s workspace %', TG_TABLE_NAME, ws, ctx_ws
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  NEW := jsonb_populate_record(NEW, jsonb_build_object('workspace_id', ws, 'team_id', team));
  RETURN NEW;
END $$;--> statement-breakpoint
-- KEYS: assigned from the counter when the writer leaves `key` NULL; a writer-supplied
-- `PREFIX-NNN` key moves the counter past it. Keys never change once written — events and
-- knowledge edges name rows by key.
CREATE OR REPLACE FUNCTION kumiai_guild_key() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_prefix text := TG_ARGV[0];
  n integer;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.key IS DISTINCT FROM OLD.key THEN
      RAISE EXCEPTION 'kumiai: % key % cannot change', TG_TABLE_NAME, OLD.key USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.key IS NULL THEN
    NEW.key := kumiai_allocate_key(NEW.workspace_id, v_prefix);
  ELSIF NEW.key ~ ('^' || v_prefix || '-[0-9]{3,9}$') THEN
    n := substr(NEW.key, length(v_prefix) + 2)::integer;
    INSERT INTO kumiai_key_counters (workspace_id, prefix, next) VALUES (NEW.workspace_id, v_prefix, n + 1)
    ON CONFLICT (workspace_id, prefix) DO UPDATE SET next = GREATEST(kumiai_key_counters.next, EXCLUDED.next);
  END IF;
  RETURN NEW;
END $$;--> statement-breakpoint
