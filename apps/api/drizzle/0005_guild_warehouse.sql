-- v_doc_stale — a current doc whose `describes`/`decides` subject has an event newer than the
-- doc's updated_at, EXCEPT the transition that closes the subject (moved -> done). Compared
-- at second precision, as the guild compares substr(ts, 1, 19).
CREATE VIEW kumiai_v_doc_stale AS
SELECT d.workspace_id,
       d.slug                AS slug,
       d.title               AS title,
       d.kind                AS kind,
       d.area                AS area,
       ke.rel                AS rel,
       ke.to_type            AS subject_type,
       ke.to_id              AS subject_id,
       date_trunc('second', d.updated_at) AS doc_updated_at,
       m.moved_at            AS subject_moved_at
  FROM kumiai_g_doc d
  JOIN kumiai_g_knowledge_edge ke
    ON ke.workspace_id = d.workspace_id
   AND ke.from_type = 'doc' AND ke.from_id = d.slug
   AND ke.rel IN ('describes', 'decides')
 CROSS JOIN LATERAL (
   SELECT MAX(date_trunc('second', e.ts)) AS moved_at FROM kumiai_g_event e
    WHERE e.workspace_id = ke.workspace_id
      AND e.subject_type = ke.to_type AND e.subject_id = ke.to_id
      AND NOT (e.verb = 'moved' AND (e.payload ->> 'to') = 'done')
 ) m
 WHERE d.status = 'current'
   AND m.moved_at > date_trunc('second', d.updated_at)
 ORDER BY subject_moved_at DESC, d.slug COLLATE "C";--> statement-breakpoint
