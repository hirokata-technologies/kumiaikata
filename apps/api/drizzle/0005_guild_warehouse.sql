-- v_brief — THE STANDUP AS FACTS: 28 rows per workspace, `value` always text, every count
-- derived from the same views the detail lists come from.
CREATE VIEW kumiai_v_brief AS
SELECT w.id AS workspace_id, f.ord, f.fact, f.value
  FROM kumiai_workspaces w
 CROSS JOIN LATERAL (VALUES
  ( 1, 'generated_at',      kumiai_iso(kumiai_utc_now())),
  ( 2, 'actor',             COALESCE((SELECT s.value FROM kumiai_guild_state s WHERE s.workspace_id = w.id AND s.key = 'actor'), 'orchestrator')),
  ( 3, 'last_checkin',      COALESCE((SELECT s.value FROM kumiai_guild_state s WHERE s.workspace_id = w.id AND s.key = 'last-checkin'), 'null')),
  ( 4, 'next',              COALESCE((SELECT n.id     FROM kumiai_v_next_task n WHERE n.workspace_id = w.id LIMIT 1), 'none')),
  ( 5, 'next_reason',       COALESCE((SELECT n.reason FROM kumiai_v_next_task n WHERE n.workspace_id = w.id LIMIT 1), 'none')),
  ( 6, 'tasks_in_progress',   (SELECT COUNT(*) FROM kumiai_tasks t WHERE t.workspace_id = w.id AND t.status = 'in-progress')::text),
  ( 7, 'tasks_todo',          (SELECT COUNT(*) FROM kumiai_tasks t WHERE t.workspace_id = w.id AND t.status = 'todo')::text),
  ( 8, 'tasks_blocked',       (SELECT COUNT(*) FROM kumiai_tasks t WHERE t.workspace_id = w.id AND t.status = 'blocked')::text),
  ( 9, 'tasks_failed',        (SELECT COUNT(*) FROM kumiai_tasks t WHERE t.workspace_id = w.id AND t.status = 'failed')::text),
  (10, 'tasks_failed_waived', (SELECT COUNT(*) FROM kumiai_v_failed_tasks v WHERE v.workspace_id = w.id AND v.waived = 1)::text),
  (11, 'tasks_done',          (SELECT COUNT(*) FROM kumiai_tasks t WHERE t.workspace_id = w.id AND t.status = 'done')::text),
  (12, 'bounties_open',       (SELECT COUNT(*) FROM kumiai_v_open_bounties v WHERE v.workspace_id = w.id)::text),
  (13, 'bounties_stuck',      (SELECT COUNT(*) FROM kumiai_v_blocked_tasks v WHERE v.workspace_id = w.id)::text),
  (14, 'requirements_open',   (SELECT COUNT(*) FROM kumiai_requirements r WHERE r.workspace_id = w.id AND r.status <> 'done')::text),
  (15, 'requirements_done',   (SELECT COUNT(*) FROM kumiai_requirements r WHERE r.workspace_id = w.id AND r.status = 'done')::text),
  (16, 'projects_open',       (SELECT COUNT(*) FROM kumiai_projects p WHERE p.workspace_id = w.id AND p.status <> 'done')::text),
  (17, 'projects_runnable',   (SELECT COUNT(*) FROM kumiai_v_projects_runnable v WHERE v.workspace_id = w.id)::text),
  (18, 'projects_worktree',   (SELECT COUNT(*) FROM kumiai_v_projects_runnable v WHERE v.workspace_id = w.id AND v.isolation = 'worktree')::text),
  (19, 'bugs_open',           (SELECT COUNT(*) FROM kumiai_v_open_bugs v WHERE v.workspace_id = w.id)::text),
  (20, 'findings_open',       (SELECT COUNT(*) FROM kumiai_v_open_findings v WHERE v.workspace_id = w.id)::text),
  (21, 'coverage_due',        (SELECT COUNT(*) FROM kumiai_v_coverage_due v WHERE v.workspace_id = w.id)::text),
  (22, 'nodes_ready',         (SELECT COUNT(*) FROM kumiai_v_ready_nodes v WHERE v.workspace_id = w.id AND v.kind = 'work')::text),
  (23, 'gates_pending',       (SELECT COUNT(*) FROM kumiai_v_gates_pending v WHERE v.workspace_id = w.id)::text),
  (24, 'plans_pending_approval', (SELECT COUNT(*) FROM kumiai_v_plans_pending_approval v WHERE v.workspace_id = w.id)::text),
  -- no (or an unreadable) last check-in counts every event, as the guild's `ts >= ''` does
  (25, 'events_since_checkin',
       (SELECT COUNT(*) FROM kumiai_event e
         WHERE e.workspace_id = w.id
           AND e.ts >= COALESCE(kumiai_try_ts((SELECT s.value FROM kumiai_guild_state s
                                                WHERE s.workspace_id = w.id AND s.key = 'last-checkin')),
                                '-infinity'::timestamp))::text),
  -- the library's three facts; docs_stale counts PAGES, not (page, subject) pairs
