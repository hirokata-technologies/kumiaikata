  (27, 'docs_stale',          (SELECT COUNT(DISTINCT v.slug) FROM kumiai_v_doc_stale v WHERE v.workspace_id = w.id)::text),
  (28, 'work_undocumented',   (SELECT COUNT(*) FROM kumiai_v_undocumented_work v WHERE v.workspace_id = w.id)::text)
 ) AS f(ord, fact, value)
 ORDER BY w.id, f.ord;
